import assert from 'node:assert/strict';
import { app, bridge, nativeAction, setSnapshot, setWorkspace, callTool, getWorkspaceContext } from './runtime.mjs';
const id = 'user-journeys/onboarding/persona-2.json';
const revision = 'a'.repeat(64);
const project={id:'b'.repeat(64),root:'/synthetic/demo',registered:true,running:true};
setWorkspace(project);
assert.throws(()=>setWorkspace({...project,registered:false}),/Select a running registered workspace/,'An unregistered project cannot bind the runtime');
setSnapshot({ catalog: { documents: [{ id, revision }] } });
const calls = [];
app.callServerTool = async input => { calls.push(input); return { structuredContent: { success: true, workspace:{id:project.id,root:project.root} } }; };
await getWorkspaceContext();
assert.deepEqual(calls.pop(), { name: 'open_workspace', arguments: {} });
assert.deepEqual(await nativeAction('addJourneyItem', ['onboarding', 'persona-2', 'goals', 'start', 'A saved item']), { success: true,workspace:{id:project.id,root:project.root} });
assert.deepEqual(calls[0], { name: 'add_journey_item', arguments: { workspace:project.id,id, revision, row: 'goals', column: 'start', text: 'A saved item' } });
const unsupported = await nativeAction('deleteJourneyItem', ['onboarding', 'persona-2']);
assert.equal(unsupported.success, false);
assert.equal(calls.length, 1);
app.getHostCapabilities = () => ({});
await assert.rejects(bridge.deliver(false, '', []), /does not support/);
app.getHostCapabilities = () => ({ message: {} });
app.sendMessage = async () => ({ isError: true });
await assert.rejects(bridge.deliver(true, 'Analyze', []), /did not deliver/);
app.getHostCapabilities = () => ({ updateModelContext: {} });
let context;
app.updateModelContext = async value => { context = value; return {}; };
await bridge.deliver(false, '', [{ id, revision, title: 'Demo', kind: 'journey', content: 'Canonical content',workspace:project.id,workspaceRoot:project.root }]);
assert.match(context.content[0].text, /Canonical content/);
assert.match(context.content[0].text, new RegExp(revision));
app.callServerTool = async () => ({structuredContent:{workspace:{id:'c'.repeat(64),root:'/synthetic/other'}}});
await assert.rejects(callTool('list_documents',{}),/another repository/);
await assert.rejects(bridge.deliver(false,'',[{workspace:'c'.repeat(64),workspaceRoot:'/synthetic/other'}]),/another workspace/);
console.log('Native SDK bridge checks passed (synthetic data only).');
